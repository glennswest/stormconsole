// The Storage page (#96), over deploy/verify-storage-view.sh. PHASE: real, refused.
const { walk } = require('./lib.cjs')
const PHASE = process.env.PHASE

walk(`storage (${PHASE})`, async (t) => {
  const page = await t.page()
  const tab = (n) => page.locator('nav.tabs button', { hasText: n }).click()
  if (PHASE === 'refused') {
    t.check(await t.open(page, '#/storage', /the engine did not answer/), 'an engine that will not answer is said', (await t.text(page)).slice(0, 400))
    t.check(/401/.test(await t.text(page)), 'with what it said')
    return
  }
  t.check(await t.open(page, '#/storage', /seed/), 'the page opens on volumes', (await t.text(page)).slice(0, 400))
  const nav = await page.evaluate(() => fetch('/api/v1/console/nav').then((r) => r.json()))
  t.check(JSON.stringify(nav.find((s) => s.label === 'Storage') || nav).includes('#/storage'), 'Storage has Overview')
  let text = await t.text(page)
  t.check(/Capacity/.test(text) && /Volumes\s*3/.test(text), 'the band of totals', text.slice(0, 300))
  const seed = page.locator('tr', { hasText: 'seed' }).first()
  t.check(/healthy/i.test(await seed.innerText()), 'a volume\'s health', await seed.innerText())
  t.check(/2 of 2/.test(await seed.innerText()), 'and its legs', await seed.innerText())
  await t.shot(page, 'storage-volumes')
  await page.locator('input[aria-label="Search volumes"]').fill('other')
  t.check(await t.until(async () => (await page.locator('tbody tr').count()) === 1), 'search narrows it')
  await page.locator('input[aria-label="Search volumes"]').fill('')
  await tab('Slabs')
  t.check(await t.until(async () => /\.img/.test(await t.text(page))), 'slabs and their drive', (await t.text(page)).slice(0, 400))
  await t.shot(page, 'storage-slabs')
  await tab('Drives')
  t.check(await t.until(async () => /ZC900/.test(await t.text(page))), 'drives: stormdrive\'s', (await t.text(page)).slice(0, 500))
  text = await t.text(page)
  const z = page.locator('tr', { hasText: 'ZC900' })
  t.check(/warning/.test(await z.innerText()) && /44 °C/.test(await z.innerText()) && /12 %/.test(await z.innerText()), 'with health, heat, wear', await z.innerText())
  t.check(/5000a098aaaa0001 7/.test(await z.innerText()), 'and where it sits')
  t.check(/the engine only/.test(text), 'and the engine\'s own')
  t.check(/dead's stormdrive did not answer|dead’s stormdrive did not answer/.test(text), 'a node that did not answer is named')
  await t.shot(page, 'storage-drives')
  await tab('Nodes')
  t.check(await t.until(async () => /verify-storage/.test(await t.text(page))), 'the node', (await t.text(page)).slice(0, 400))
  t.check(/this node/.test(await t.text(page)), 'marked as this one')
  await tab('Enclosures')
  t.check(await t.until(async () => /5000a098aaaa0001/.test(await t.text(page))), 'an enclosure', (await t.text(page)).slice(0, 400))
  const e = await page.locator('tr', { hasText: '5000a098aaaa0001' }).innerText()
  t.check(/1 of 2/.test(e) && /4 of 4/.test(e) && /51 °C/.test(e) && /3 need a format/.test(e), 'PSUs, fans, heat, and what needs a format', e)
  await t.shot(page, 'storage-enclosures')
  await tab('Volumes')
  await page.locator('tr', { hasText: 'seed' }).first().getByRole('link').click()
  t.check(await t.until(async () => /seed/.test(await t.text(page)) && !/Storage objects/.test(await page.content()), 20000), 'a volume opens', (await t.text(page)).slice(0, 300))
  t.check(!/not found|No such/i.test(await t.text(page)), 'to its own row')
})
